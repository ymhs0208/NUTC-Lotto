import { test } from 'node:test';
import assert from 'node:assert/strict';
import { localWorker } from '../scripts/local-worker';
import { hashPassword } from '../server/credentials';
test('anonymous results expose only drawn public columns and follow draw/reset without modifying state', { timeout: 180000 }, async () => {
  const worker = await localWorker();
  try {
    await worker.start();
    const req = worker.request;
    const initial = await req('/api/public/results');
    assert.equal(initial.status, 200);
    assert.equal(initial.data.success, true);
    assert.deepEqual(initial.data.results, []);
    assert.ok(initial.data.domains.length);
    await worker.setup({ action: 'accounts', accounts: [{ id: 'results-admin', email: 'results@example.test', role: 'admin', password_hash: await hashPassword('Abc12345') }] });
    const login = await req('/api/auth/verify', { username: 'results@example.test', password: 'Abc12345', targetView: 'admin' });
    const admin = (path: string, body?: unknown) => req(path, body, login.cookie);
    const fields = ['企業智慧化', '其他領域'];
    const config = await admin('/api/domain-configs', { version: 0, domainConfigs: fields.map((field, i) => ({ id: `d${i}`, field, groupCount: 2 })) });
    const projects = Array.from({ length: 6 }, (_, i) => ({ id: `p${i}`, seq_no: String(i), education_system: '四技', department: '測試系', class_name: '甲', advisor: '私人老師', field: fields[i < 4 ? 0 : 1], original_code: '', project_title: `公開專題 ${i}`, leader_id: `private-student-${i}`, password: 'PrivatePass123', evaluators: ['私人評審'] }));
    const roster = await admin('/api/projects', { version: config.data.version, projects });
    assert.equal(roster.status, 200);
    const path = `/api/public/results?field=${encodeURIComponent(fields[0])}`;
    assert.deepEqual((await req(path)).data.results, []);
    assert.equal((await req('/api/public/results?field[]=invalid')).status, 400);
    assert.equal((await req(`/api/public/results?field=${'a'.repeat(513)}`)).status, 400);
    assert.deepEqual((await req('/api/public/results?field=%27%20OR%201%3D1--')).data.results, []);
    const draw = await admin('/api/lottery/draw', { fields: [fields[0]], version: roster.data.version });
    assert.equal(draw.status, 200);
    const before = (await admin('/api/state')).data;
    const published = await req(path);
    assert.equal(published.status, 200);
    assert.equal(published.cookie, '');
    assert.equal(published.headers['cache-control'], 'no-store');
    assert.deepEqual(published.data.domains, fields);
    assert.equal(published.data.version, draw.data.version);
    const expected = draw.data.projects.filter((p: any) => p.field === fields[0]).sort((a: any, b: any) => a.assigned_group - b.assigned_group || a.draw_order - b.draw_order).map((p: any) => ({ draw_code: p.draw_code, assigned_group: p.assigned_group, project_title: p.project_title }));
    assert.deepEqual(published.data.results, expected);
    for (const row of published.data.results) assert.deepEqual(Object.keys(row).sort(), ['assigned_group', 'draw_code', 'project_title']);
    assert.ok(!JSON.stringify(published.data).includes('private-student'));
    assert.ok(!JSON.stringify(published.data).includes('PrivatePass'));
    assert.deepEqual((await req(`/api/public/results?field=${encodeURIComponent(fields[1])}`)).data.results, []);
    assert.deepEqual((await req('/api/public/results')).data.results, []);
    assert.deepEqual((await admin('/api/state')).data, before);
    const reset = await admin('/api/lottery/reset', { fields: [fields[0]], version: draw.data.version });
    assert.equal(reset.status, 200);
    const after = (await req(path)).data;
    assert.deepEqual(after.results, []);
    assert.equal(after.version, reset.data.version);
  } finally { await worker.dispose(); }
});
